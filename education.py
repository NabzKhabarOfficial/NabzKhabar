# ------------------------------------------------------------------ selection
def _by_id():
    return {p["id"]: p for p in EDUCATIONAL_POSTS}


def pick(state):
    """Next lesson in bank order that has not been published yet (resets after the full bank)."""
    done = set(state.get("education_done") or [])
    for item in EDUCATIONAL_POSTS:
        if item["id"] not in done:
            return item
    return EDUCATIONAL_POSTS[0]


def mark_done(state, item, number):
    done = [i for i in (state.get("education_done") or []) if i in _by_id()]
    if item["id"] not in done:
        done.append(item["id"])
    if len(done) >= len(EDUCATIONAL_POSTS):
        done = []  # full cycle published: start again next time
    state["education_done"] = done
    state["education_count"] = int(number)
    return state


# ------------------------------------------------------------------ caption
def _fa(n):
    return str(n).translate(FA_NUM)


def caption(item, number=None):
    emoji, _, _, tag = CATEGORIES[item["cat"]]
    head = f"🎓 نبض آموزش | {emoji} {item['cat']}"
    if number:
        head += f" · قسمت {_fa(number)}"
    steps = "\n".join(f"{_fa(i)}. {s}" for i, s in enumerate(item["steps"], 1))
    parts = [head, "", f"📌 {item['title']}", "", item["hook"], "", item["body"], "",
             "✅ چه کار کنیم؟", steps, "", f"💡 بدانید: {item['fact']}", "",
             f"📚 منبع: {item['src']}", f"{tag} #نبض_آموزش", f"📢 {HANDLE}"]
    text = "\n".join(parts)
    if len(text) > 1000:  # Telegram photo captions are limited; drop the long explanation first
        parts = parts[:6] + parts[8:]
        text = "\n".join(parts)
    return text[:1000]


# ------------------------------------------------------------------ image card
def _wrap(d, text, f, max_w, tlen):
    lines, cur = [], ""
    for word in str(text).split():
        trial = (cur + " " + word).strip()
        if not cur or tlen(d, trial, f) <= max_w:
            cur = trial
        else:
            lines.append(cur)
            cur = word
    if cur:
        lines.append(cur)
    return lines


