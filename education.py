def already_posted_today(history_lines, day_key):
    marker = EDU_HISTORY_MARKER + day_key
    return any(line.strip() == marker for line in history_lines)


def mark_posted(day_key):
    import v13_standalone as main
    marker = EDU_HISTORY_MARKER + day_key
    try:
        with open(main.HISTORY_FILE, "a", encoding="utf-8") as f:
            f.write(marker + "\n")
        return True
    except Exception as e:
        print(f"Education history error: {e}")
        return False


def post_daily_education():
    """Old standalone text sender, kept for manual runs. The channel uses daily_boards."""
    import v13_standalone as main
    now = datetime.now(timezone.utc)
    day_key = now.strftime("%Y-%m-%d")
    try:
        with open(main.HISTORY_FILE, "r", encoding="utf-8") as f:
            history_lines = f.read().splitlines()
    except FileNotFoundError:
        history_lines = []
    if already_posted_today(history_lines, day_key):
        print("EDUCATION: already published today.")
        return False
    item = EDUCATIONAL_POSTS[now.toordinal() % len(EDUCATIONAL_POSTS)]
    if main.send_message(caption(item)):
        mark_posted(day_key)
        print(f"EDUCATION PUBLISHED: {item['title']}")
        return True
    print("EDUCATION: publication failed.")
    return False


