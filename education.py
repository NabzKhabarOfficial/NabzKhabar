        dc._glow(img, (W - 150, 120), 230, accent, 60)
        subtitle = f"{item['cat']} · قسمت {_fa(number)}" if number else item["cat"]
        dc._header(img, "نبض آموزش", subtitle, dc.fa(jalali_date), accent)
        d = ImageDraw.Draw(img)

        # title
        for line in title_l:
            dc.rtl(d, (x1, y), line, f_title, (255, 255, 255))
            y += LH_T
        y += 30

        # hook box with accent bar
        d.rounded_rectangle([x0, y, x1, y + h_hook], radius=26, fill=dc.CARD, outline=dc.LINE, width=2)
        d.rounded_rectangle([x1 - 12, y + 22, x1 - 4, y + h_hook - 22], radius=4, fill=accent)
        yy = y + 28
        for line in hook_l:
            dc.rtl(d, (x1 - 36, yy), line, f_hook, dc.INK)
            yy += LH_H
        y += h_hook + 34

        # explanation
        for line in body_l:
            dc.rtl(d, (x1, y), line, f_body, (196, 205, 220))
            y += LH_B
        y += 50

        # steps
        dc.rtl(d, (x1, y), "چه کار کنیم؟", f_lbl, accent)
        y += 50
        for i, lines in enumerate(steps_l, 1):
            bh = max(1, len(lines)) * LH_S + 52
            d.rounded_rectangle([x0, y, x1, y + bh], radius=22, fill=dc.CARD if i % 2 else dc.CARD2)
            cx, cy = x1 - 56, y + bh / 2
            d.ellipse([cx - 30, cy - 30, cx + 30, cy + 30], fill=accent)
            d.text((cx, cy), dc.fa(i), font=dc.font(32), fill=(255, 255, 255), anchor="mm")
            ty = y + 26
            for line in lines:
                dc.rtl(d, (x1 - 112, ty), line, f_step, dc.INK)
                ty += LH_S
            y += bh + 16
        y += 24

        # good-to-know box
        d.rounded_rectangle([x0, y, x1, y + h_fact], radius=26, outline=accent, width=3, fill=(14, 19, 30))
        dc.rtl(d, (x1 - 36, y + 24), "بدانید", dc.font(28), accent)
        yy = y + 72
        for line in fact_l:
            dc.rtl(d, (x1 - 36, yy), line, f_fact, dc.INK)
            yy += LH_F
        y += h_fact

        dc._footer(img, total - 110, f"منبع: {item['src']}"[:60])
        img.save(out_path, quality=92)
        return out_path
